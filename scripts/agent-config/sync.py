#!/usr/bin/env python3
"""Share Claude guidance without changing its sources. Python standard library only.

Adapted from OpenData's scripts/agent-config/sync.py (48e2ba7ed).
Generates AGENTS.md, Antigravity rules, and relative skill links. --check
writes nothing and returns 1 for drift, 2 for invalid inputs or collisions.
"""

from __future__ import annotations

import argparse
import json
import os
from pathlib import Path
import re
import sys

MARKER = "GENERATED by scripts/agent-config/sync.py"


class ConfigError(Exception):
    pass


def repo_root() -> Path:
    # Works in linked worktrees and pre-commit, even with GIT_DIR set.
    return Path(__file__).resolve().parents[2]


def read_manifest(path: Path) -> dict[str, list[str]]:
    entries: dict[str, list[str]] = {"rule": [], "skill": []}
    for lineno, raw in enumerate(path.read_text().splitlines(), 1):
        line = raw.split("#", 1)[0].strip()
        if not line:
            continue
        match = re.fullmatch(r"(rule|skill):([A-Za-z0-9_./-]+)", line)
        if not match:
            raise ConfigError(f"{path.name}:{lineno}: invalid entry {line!r}")
        kind, name = match.groups()
        if any(part in ("", ".", "..") for part in name.split("/")):
            raise ConfigError(f"{path.name}:{lineno}: expected a relative source path")
        if (kind == "skill" and "/" in name) or (kind == "rule" and not name.endswith(".md")):
            raise ConfigError(f"{path.name}:{lineno}: invalid {kind} name")
        if name in entries[kind]:
            raise ConfigError(f"{path.name}:{lineno}: duplicate {line}")
        entries[kind].append(name)
    return entries


def scalar(value: str) -> str:
    value = value.strip()
    if value.startswith('"'):
        try:
            result = json.loads(value)
        except ValueError as exc:
            raise ConfigError(f"invalid quoted scalar: {value!r}") from exc
        if not isinstance(result, str):
            raise ConfigError(f"expected text: {value!r}")
        return result
    if value.startswith("'"):
        if not value.endswith("'") or len(value) < 2:
            raise ConfigError(f"invalid quoted scalar: {value!r}")
        return value[1:-1].replace("''", "'")
    if value.startswith(("[", "{", "&", "*", "!")):
        raise ConfigError(f"unsupported YAML scalar: {value!r}; quote it")
    return re.split(r"\s+#", value, maxsplit=1)[0].strip()


def frontmatter(text: str) -> tuple[dict, str]:
    """The sources use scalars and block lists; also accept JSON inline lists.

    Fail on unsupported YAML rather than silently changing rule activation.
    """
    if not text.startswith("---\n"):
        return {}, text
    end = text.find("\n---\n", 3)
    if end < 0:
        raise ConfigError("unterminated frontmatter")
    lines = text[4:end].splitlines()
    data: dict = {}
    i = 0
    while i < len(lines):
        line = lines[i]
        i += 1
        if not line.strip() or line.lstrip().startswith("#"):
            continue
        match = re.fullmatch(r"([A-Za-z_][\w-]*):(.*)", line)
        if not match:
            raise ConfigError(f"unsupported frontmatter line: {line!r}")
        key, rest = match.groups()
        rest = rest.strip()
        if key in data:
            raise ConfigError(f"duplicate frontmatter key: {key}")
        if not rest or rest.startswith("#"):
            items = []
            while i < len(lines) and (not lines[i].strip() or lines[i].startswith(" ")):
                item = lines[i].strip()
                i += 1
                if not item or item.startswith("#"):
                    continue
                if not item.startswith("- "):
                    raise ConfigError(f"expected a list under {key}: {item!r}")
                items.append(scalar(item[2:]))
            data[key] = items
        elif rest.startswith("["):
            try:
                data[key] = json.loads(rest)
            except ValueError as exc:
                # Claude commands also use e.g. argument-hint: [path-or-filter].
                # Quoted lists use JSON above so commas within globs stay intact.
                if re.fullmatch(r"\[[A-Za-z0-9_./* -]+(?:,[A-Za-z0-9_./* -]+)*\]", rest):
                    data[key] = [scalar(item) for item in rest[1:-1].split(",")]
                else:
                    raise ConfigError(f"unsupported inline list: {rest!r}") from exc
        elif rest in (">", ">-", "|", "|-"):
            block = []
            while i < len(lines) and (not lines[i].strip() or lines[i].startswith(" ")):
                block.append(lines[i].strip())
                i += 1
            data[key] = (" " if rest.startswith(">") else "\n").join(block).strip()
        else:
            data[key] = scalar(rest)
    return data, text[end + 5:]


def read_source(path: Path) -> tuple[dict, str]:
    try:
        return frontmatter(path.read_text())
    except ConfigError as exc:
        raise ConfigError(f"{path}: {exc}") from exc


def rule_paths(metadata: dict) -> list[str]:
    if "paths" not in metadata:
        return []
    paths = metadata["paths"]
    if isinstance(paths, str):
        paths = [paths]
    if not isinstance(paths, list) or not paths or any(not isinstance(p, str) or not p for p in paths):
        raise ConfigError("paths must contain one or more nonempty glob strings")
    return paths


def expand_braces(pattern: str) -> list[str]:
    match = re.search(r"\{([^{}]*)\}", pattern)
    if not match:
        if "{" in pattern or "}" in pattern:
            raise ConfigError(f"unbalanced glob braces: {pattern}")
        return [pattern]
    return [expanded for alt in match[1].split(",")
            for expanded in expand_braces(pattern[:match.start()] + alt + pattern[match.end():])]


def antigravity_globs(paths: list[str]) -> list[str]:
    globs = []
    for path in paths:
        for pattern in expand_braces(path):
            if "," in pattern:
                raise ConfigError(f"Antigravity cannot represent a comma in glob {path!r}")
            # OpenData's agy adapter uses absolute-path globs, as probed there.
            glob = pattern if pattern.startswith("**") else f"**/{pattern}"
            if glob not in globs:
                globs.append(glob)
    return globs


def table_cell(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " ")


def desired_state(root: Path) -> dict[Path, tuple[str, str]]:
    entries = read_manifest(root / "scripts/agent-config/shared.txt")
    want: dict[Path, tuple[str, str]] = {}
    rows = []
    for rel in sorted(entries["rule"]):
        src = f".claude/rules/{rel}"
        metadata, body = read_source(root / src)
        paths = rule_paths(metadata)
        description = metadata.get("description") or next(
            (line[2:].strip() for line in body.splitlines() if line.startswith("# ")),
            Path(rel).stem,
        )
        if not isinstance(description, str):
            raise ConfigError(f"{src}: description must be text")
        head = ["---", f"trigger: {'glob' if paths else 'always_on'}",
                f"description: {json.dumps(description, ensure_ascii=False)}"]
        if paths:
            head.append(f"globs: {json.dumps(','.join(antigravity_globs(paths)))}")
        head += ["---", f"<!-- {MARKER} from {src}. Edit the source, then run make agent-config. -->"]
        dest = root / ".agents/rules" / rel.replace("/", "-")
        if dest in want:
            raise ConfigError(f"rule output collision: {dest.name}")
        want[dest] = ("file", "\n".join(head) + "\n" + body)
        applies = ", ".join(f"`{table_cell(p)}`" for p in paths) if paths else "All tasks"
        rows.append(f"| {applies} | [{rel}]({src}) |")

    for name in sorted(entries["skill"]):
        src = root / ".claude/skills" / name / "SKILL.md"
        metadata, _ = read_source(src)
        if not all(isinstance(metadata.get(key), str) and metadata[key] for key in ("name", "description")):
            raise ConfigError(f"{src}: skill needs name and description")
        want[root / ".agents/skills" / name] = ("link", f"../../.claude/skills/{name}")

    commands = []
    for path in sorted((root / ".claude/commands").glob("*.md")):
        metadata, _ = read_source(path)
        description = metadata.get("description")
        if not isinstance(description, str) or not description:
            raise ConfigError(f"{path}: command needs a description")
        commands.append(f"| [{path.stem}]({path.relative_to(root).as_posix()}) | {table_cell(description)} |")

    compatibility = """## Other agent harnesses

`CLAUDE.md` and `.claude/` remain the canonical guidance. This file is generated;
edit those sources, then run `make agent-config`. Commit the generated outputs too.
See [agent config maintenance](scripts/agent-config/README.md).

All paths here are relative to the repository root, including when your session
starts in a subdirectory. The short `rules/...` entries above refer to `.claude/rules/...`.
Instructions explicitly about Claude Code tools or isolation apply to that harness.
Other harnesses may work directly in the repo; there is no Claude-only driver role.

### Rules to read before working

Claude attaches rules automatically by path. In Codex or another harness without
that mechanism, read every source rule below whose glob matches a file you will
work on, including tests. Re-evaluate when the task touches additional paths.
Patterns are repository-relative; `**` includes nested directories. Rules with no
path restriction apply to all tasks. Read only applicable rules, not the whole tree.
Antigravity receives generated glob rules in `.agents/rules/`; these are not a
Codex auto-loading mechanism.

| Matching files | Canonical rule |
| --- | --- |
""" + "\n".join(rows) + """

### Skills and commands

Shared skills are discovered through relative links in `.agents/skills/`, pointing
at `.claude/skills/`. Their instructions and supporting resources remain there.
For guidance that references an unavailable external plugin/tool, use an available
equivalent and report any verification you cannot perform.

The following are existing workflow instructions. Read the linked command when
asked to perform that workflow and run its shell commands with your harness's tools.
Claude slash-command syntax is not required; `$ARGUMENTS` means the user's supplied
path or filter. These links do not automatically invoke workflows.

| Workflow instructions | Purpose |
| --- | --- |
""" + "\n".join(commands) + """

### Checks outside Claude

Claude's `.claude/settings.json` permissions and lifecycle hooks do not execute
automatically in other harnesses. At session start, inspect `git status` and the
current branch; check `plan/PROGRESS.md` and, for UI work, `plan/design-system.md`.
Follow the source rules, including generated-file and import boundaries, explicitly.

Use the existing commands: `bun run format` / `cargo fmt --all` for formatting,
`bun run lint` for frontend boundaries, scoped tests while iterating, and the
verification rules for completion. `make hooks` installs the existing Git hooks,
which include secret scanning and macOS pre-push checks regardless of harness.
`make check` is the shared quality gate; bindings and frontend performance checks
remain `make bindings-check` and `make e2e-perf` when required by existing guidance.
Guidance discovery does not provide runtime hook enforcement or auto-approval.
"""
    source = (root / "CLAUDE.md").read_text()
    want[root / "AGENTS.md"] = (
        "file", f"<!-- {MARKER} from CLAUDE.md and .claude/. Do not edit. -->\n\n"
        + source.rstrip() + "\n\n" + compatibility,
    )
    return want


def is_managed(path: Path) -> bool:
    if path.is_symlink():
        return re.fullmatch(r"\.\./\.\./\.claude/skills/[A-Za-z0-9_.-]+", os.readlink(path)) is not None
    if path.is_file():
        return f"<!-- {MARKER} " in path.read_text()[:4096]
    return False


def plan_changes(root: Path, want: dict) -> list[tuple[str, Path, tuple[str, str] | None]]:
    changes = []
    for path, spec in sorted(want.items()):
        # Never follow an output-directory symlink out of this checkout.
        for parent in path.parents:
            if parent == root:
                break
            if parent.is_symlink():
                raise ConfigError(f"output directory is a symlink: {parent}")
        exists = path.exists() or path.is_symlink()
        if exists:
            if not is_managed(path):
                raise ConfigError(f"refusing to overwrite unmanaged file: {path.relative_to(root)}")
            kind, value = spec
            if kind == "link":
                matches = path.is_symlink() and os.readlink(path) == value
            else:
                matches = not path.is_symlink() and path.read_text() == value
            if matches:
                continue
        changes.append(("update" if exists else "create", path, spec))
    for dirname in (".agents/rules", ".agents/skills"):
        directory = root / dirname
        if directory.is_symlink() or directory.parent.is_symlink():
            raise ConfigError(f"output directory is a symlink: {directory}")
        if directory.is_dir():
            for path in sorted(directory.iterdir()):
                if path not in want and is_managed(path):
                    changes.append(("remove", path, None))
    return changes


def apply(changes: list) -> None:
    for action, path, spec in changes:
        if path.exists() or path.is_symlink():
            path.unlink()
        if action == "remove":
            continue
        kind, value = spec
        path.parent.mkdir(parents=True, exist_ok=True)
        if kind == "link":
            path.symlink_to(value)
        else:
            path.write_text(value)


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="report drift without writing")
    args = parser.parse_args(argv)
    root = repo_root()
    try:
        changes = plan_changes(root, desired_state(root))
        if args.check and changes:
            print("agent-config is stale; run make agent-config:", file=sys.stderr)
            for action, path, _ in changes:
                print(f"  {action:6} {path.relative_to(root)}", file=sys.stderr)
            return 1
        if not args.check:
            apply(changes)
            for action, path, _ in changes:
                print(f"{action:6} {path.relative_to(root)}")
        print("agent-config: up to date")
        return 0
    except (ConfigError, OSError, UnicodeError) as exc:
        print(f"agent-config: {exc}", file=sys.stderr)
        return 2


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
